# ==============================================================================
# DISASTER RESPONSE SYSTEM - AUTOMATED WINDOWS EXE PACKAGING PIPELINE
# Build Script: build-exe.ps1
# Platform: Windows 10 / 11 x64
# Requirements: Java 25 JDK, PowerShell 5.1+, MySQL 8.0+
# ==============================================================================

param(
    [switch]$SkipTests = $false
)

$ErrorActionPreference = "Stop"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$ProjectRoot = Resolve-Path "$ScriptDir\.."

Set-Location $ProjectRoot

Write-Host "===============================================================================" -ForegroundColor Cyan
Write-Host "  DISASTER RESPONSE SYSTEM — WINDOWS STANDALONE EXE PACKAGING" -ForegroundColor Cyan
Write-Host "===============================================================================" -ForegroundColor Cyan
Write-Host "Project Root: $ProjectRoot"
Write-Host "Target Release Dir: $ScriptDir"
Write-Host ""

# 1. Run Pre-build Tests
if (-not $SkipTests) {
    Write-Host "[1/5] Executing Maven Test Suite (All 39 unit/integration tests)..." -ForegroundColor Yellow
    & ".\mvnw.cmd" test
    if ($LASTEXITCODE -ne 0) {
        Write-Error "Maven test suite failed. Aborting packaging to prevent flawed build."
        exit 1
    }
    Write-Host "[PASS] All tests passed successfully." -ForegroundColor Green
} else {
    Write-Host "[1/5] Skipping test execution (-SkipTests enabled)..." -ForegroundColor Yellow
}

# 2. Package Spring Boot Fat JAR
Write-Host "`n[2/5] Compiling and Packaging Executable Spring Boot JAR..." -ForegroundColor Yellow
& ".\mvnw.cmd" package -DskipTests
if ($LASTEXITCODE -ne 0) {
    Write-Error "Maven package failed."
    exit 1
}
$jarPath = "target\demo-0.0.1-SNAPSHOT.jar"
if (-not (Test-Path $jarPath)) {
    Write-Error "JAR archive missing at $jarPath"
    exit 1
}
Write-Host "[PASS] Packaged $jarPath" -ForegroundColor Green

# 3. Compile Native C# Server Controller
Write-Host "`n[3/5] Compiling Native C# GUI Server Controller (DisasterResponseSystem.exe)..." -ForegroundColor Yellow
$cscPath = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path $cscPath)) {
    $cscPath = "csc.exe"
}
& $cscPath /target:winexe /platform:x64 /optimize+ /out:"$ProjectRoot\DisasterResponseSystem.exe" "src\main\csharp\DisasterResponseSystem.cs"
if ($LASTEXITCODE -ne 0) {
    Write-Error "C# compilation failed."
    exit 1
}
Write-Host "[PASS] Native GUI Controller compiled successfully." -ForegroundColor Green

# 4. Generate App-Image via JPackage
Write-Host "`n[4/5] Generating Self-Contained App Image via Java 25 jpackage..." -ForegroundColor Yellow
$jpOut = "$ScriptDir\jpackage-out"
if (Test-Path $jpOut) { Remove-Item $jpOut -Recurse -Force }
jpackage --type app-image --name DisasterResponseSystem --input target --main-jar demo-0.0.1-SNAPSHOT.jar --dest $jpOut
if ($LASTEXITCODE -ne 0) {
    Write-Error "jpackage app-image generation failed."
    exit 1
}

# Assemble release\app-image
$appImage = "$ScriptDir\app-image"
if (Test-Path $appImage) { Remove-Item $appImage -Recurse -Force }
New-Item -ItemType Directory -Path "$appImage\server" -Force | Out-Null
New-Item -ItemType Directory -Path "$appImage\uploads\incident-media" -Force | Out-Null

# Copy minimal JRE runtime generated by jlink
if (-not (Test-Path "$ProjectRoot\target\runtime\bin\java.exe")) {
    jlink --add-modules java.base,java.sql,java.naming,java.desktop,java.management,java.security.jgss,java.instrument,java.net.http,jdk.unsupported,jdk.management --strip-debug --no-man-pages --no-header-files --output "$ProjectRoot\target\runtime"
}
Copy-Item -Path "$ProjectRoot\target\runtime" -Destination "$appImage\runtime" -Recurse -Force
Copy-Item -Path $jarPath -Destination "$appImage\server\demo-0.0.1-SNAPSHOT.jar" -Force
Copy-Item -Path "$ProjectRoot\DisasterResponseSystem.exe" -Destination "$appImage\DisasterResponseSystem.exe" -Force
Copy-Item -Path "$jpOut\DisasterResponseSystem\DisasterResponseSystem.exe" -Destination "$appImage\DisasterServerBackend.exe" -Force

# Copy configuration and helper scripts (credentials kept external via env or %LOCALAPPDATA%\DisasterResponseSystem\application-local.properties)
$props = @'
spring.datasource.url=jdbc:mysql://localhost:3306/disaster_management?createDatabaseIfNotExist=true&useSSL=false&allowPublicKeyRetrieval=true&serverTimezone=UTC
spring.datasource.username=${SPRING_DATASOURCE_USERNAME:root}
spring.datasource.password=${SPRING_DATASOURCE_PASSWORD:}
spring.datasource.driver-class-name=com.mysql.cj.jdbc.Driver
server.port=8080
server.address=0.0.0.0
app.media.upload-dir=uploads/incident-media
app.server.lifecycle.test-mode=false
app.server.lifecycle.exit-jvm-on-shutdown=true
'@
Set-Content -Path "$appImage\server\application.properties" -Value $props -Encoding UTF8

$firewallBat = @"
@echo off
title Configure Windows Firewall for Disaster Response System
net session >nul 2>&1
if %ERRORLEVEL% NEQ 0 (
    echo [ERROR] Administrative privileges required. Right-click and select 'Run as administrator'.
    pause
    exit /b 1
)
netsh advfirewall firewall add rule name="DisasterResponseSystem_Port8080" dir=in action=allow protocol=TCP localport=8080 profile=private,domain
echo [SUCCESS] Windows Firewall port 8080 opened for local Wi-Fi / LAN devices.
pause
"@
Set-Content -Path "$appImage\setup-firewall.bat" -Value $firewallBat -Encoding ASCII

$startBat = @"
@echo off
title Disaster Response System - Console Server
cd /d "%~dp0"
if exist "runtime\bin\java.exe" (
    set "JAVA_CMD=runtime\bin\java.exe"
) else (
    set "JAVA_CMD=java"
)
"%JAVA_CMD%" -XX:TieredStopAtLevel=1 -Dserver.port=8080 -Dserver.address=0.0.0.0 -jar server\demo-0.0.1-SNAPSHOT.jar
pause
"@
Set-Content -Path "$appImage\start-server.bat" -Value $startBat -Encoding ASCII

# 5. Build NSIS Installer EXE
Write-Host "`n[5/5] Compiling Windows Setup Installer (DisasterResponseSystem-Setup.exe)..." -ForegroundColor Yellow
$makensis = "C:\Users\Lenovo\AppData\Local\electron-builder\Cache\nsis\nsis-3.0.4.1\makensis.exe"
if (Test-Path $makensis) {
    & $makensis "$ProjectRoot\scripts\installer.nsi"
    if ($LASTEXITCODE -eq 0) {
        Write-Host "[PASS] Installer compiled: $ScriptDir\DisasterResponseSystem-Setup.exe" -ForegroundColor Green
    } else {
        Write-Warning "NSIS compiler exited with code $LASTEXITCODE. App-image is fully functional."
    }
} else {
    Write-Warning "makensis.exe not found at default cache path. Portable app-image is ready."
}

Write-Host "`n===============================================================================" -ForegroundColor Green
Write-Host "  BUILD COMPLETE: Distributable Windows Application Ready!" -ForegroundColor Green
Write-Host "===============================================================================" -ForegroundColor Green
Write-Host "Release Directory: $ScriptDir"
Write-Host "  - Windows Setup Installer:  $ScriptDir\DisasterResponseSystem-Setup.exe"
Write-Host "  - Portable App-Image Dir:   $ScriptDir\app-image\"
Write-Host "  - Desktop GUI Launcher:     $ScriptDir\app-image\DisasterResponseSystem.exe"
Write-Host ""
